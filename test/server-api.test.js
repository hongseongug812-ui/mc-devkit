'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs-extra');
const os = require('os');
const path = require('path');
const WebSocket = require('ws');
const {fabric}=require('./jar-fixture');

test('real HTTP distribution authenticates downloads and protects management operations', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'devkit-api-'));
  process.env.DEVKIT_DATA_DIR = root;
  const servers = path.join(root,'servers');
  await fs.writeJson(path.join(root,'config.json'), { serverDir:servers, serverFolder:'shoot', projectDir:path.join(root,'project'), serverType:'fabric', paperVersion:'26.3', memory:'2G' });
  const { startServer, getOwnerToken, isUpdateIdle } = require('../server');
  const server = await startServer(0);
  t.after(async () => { await server.shutdown(); await fs.remove(root); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = async (url, opts={}) => {
    const response=await fetch(base+url,opts);
    return { status:response.status, data:await response.json() };
  };
  assert.equal((await request('/api/status')).data.ownerToken,undefined);
  assert.equal((await request('/api/config')).data.rconPassword,undefined);
  assert.equal((await request('/api/server/start',{method:'POST'})).status,401);
  assert.equal((await request('/api/modpack')).status,401);
  assert.equal((await request('/api/server-properties')).status,401);
  const ownerToken=getOwnerToken();
  const socket = new WebSocket(base.replace('http','ws'));
  const messages=[];
  const auth = new Promise((resolve,reject)=>{
    socket.on('message',raw=>{const msg=JSON.parse(raw);messages.push(msg);if(msg.type==='AUTH_OK')resolve(msg);});
    socket.on('error',reject);
  });
  socket.on('open',()=>socket.send(JSON.stringify({type:'AUTH',token:ownerToken,name:'Test host'})));
  await auth;
  await new Promise(resolve=>setTimeout(resolve,30));
  assert.ok(messages.find(m=>m.type==='TEAM_UPDATE').clients.every(c=>c.id!==ownerToken));
  const headers = { 'X-DevKit-Token':ownerToken,'Content-Type':'application/json' };
  await fs.ensureDir(path.join(servers,'shoot','client-mods'));
  await fs.writeFile(path.join(servers,'shoot','client-mods','creator.jar'),fabric());
  const pack=await request('/api/modpack/publish',{method:'POST',headers,body:JSON.stringify({name:'Test',autoPublish:false,loaderVersion:'0.18.4'})});
  assert.equal(pack.status,200);
  const id=pack.data.id,token=pack.data.token;
  assert.equal((await request(`/api/packs/${id}/manifest`)).status,401);
  const downloadHeaders={'X-Pack-Token':token,'X-DevKit-Version':'1.9.0','Content-Type':'application/json'};
  assert.equal((await request(`/api/packs/${id}/manifest`,{headers:downloadHeaders})).status,404);
  assert.equal((await request('/api/modpack/promote',{method:'POST',headers,body:JSON.stringify({id,revision:pack.data.pending.manifest.revision})})).status,200);
  assert.equal(await isUpdateIdle(),true);
  assert.equal((await request('/api/modpack/mode',{method:'POST',headers,body:JSON.stringify({id,mode:'filming'})})).status,200);
  assert.equal(await isUpdateIdle(),false);
  await request('/api/modpack/mode',{method:'POST',headers,body:JSON.stringify({id,mode:'review'})});
  assert.equal((await request(`/api/packs/${id}/manifest`,{headers:{'X-Pack-Token':token}})).status,426);
  const manifest=await request(`/api/packs/${id}/manifest`,{headers:downloadHeaders});
  assert.equal(manifest.status,200);
  const blob=await fetch(`${base}/api/packs/${id}/files/${manifest.data.files[0].sha256}`,{headers:downloadHeaders});
  assert.equal(blob.status,200);assert.deepEqual(Buffer.from(await blob.arrayBuffer()),fabric());
  const { ModSync } = require('../core/mod-sync');
  const participant = new ModSync(path.join(root,'participant'), { isRunning:async()=>false });
  const instance = path.join(root,'game');await fs.ensureDir(instance);
  await fs.writeJson(path.join(instance,'minecraftinstance.json'),{gameVersion:'26.3',baseModLoader:{name:'fabric-0.18.4'}});
  await participant.join(`${base}/?join=${id}#token=${token}`,instance,'official');
  assert.equal(participant.list()[0].status,'pending');
  let launches=0;
  await participant.startGame(participant.list()[0].key,async()=>{launches++;return {launched:true};});
  assert.equal(launches,1);
  assert.equal(participant.list()[0].status,'updated');
  assert.deepEqual(await fs.readFile(path.join(instance,'mods','creator.jar')),fabric());
  const ready=await request('/api/modpack',{headers});assert.equal(ready.data.participants[0].ready,true);
  await fs.writeFile(path.join(servers,'shoot','client-mods','creator.jar'),fabric('2.0.0'));
  const next=await request('/api/modpack/publish',{method:'POST',headers,body:JSON.stringify({name:'Test',autoPublish:false})});
  assert.equal(next.status,200);
  assert.equal((await request('/api/modpack/promote',{method:'POST',headers,body:JSON.stringify({id,revision:next.data.pending.manifest.revision})})).status,200);
  await participant.sync(participant.list()[0].key);
  assert.deepEqual(await fs.readFile(path.join(instance,'mods','creator.jar')),fabric('2.0.0'));
  assert.equal((await request('/api/packs/'+id+'/report',{method:'POST',headers:downloadHeaders,body:JSON.stringify({clientId:'a'.repeat(32),status:'current',revision:next.data.pending.manifest.revision})})).status,200);
  const fixed=await request('/api/tunnel/settings',{method:'POST',headers,body:JSON.stringify({mode:'named',origin:'https://studio.example.com',token:'example_token'})});assert.equal(fixed.status,200);assert.equal(fixed.data.token,undefined);assert.equal(fixed.data.hasToken,true);
  assert.equal((await request('/api/modpack/invite',{method:'POST',headers,body:JSON.stringify({id,action:'rotate'})})).status,200);
  assert.equal((await request(`/api/packs/${id}/manifest`,{headers:downloadHeaders})).status,401);
  await participant.close();
  assert.equal((await request('/api/config',{method:'POST',headers:downloadHeaders,body:JSON.stringify({memory:'8G'})})).status,401);
  assert.equal((await request('/api/config',{method:'POST',headers,body:JSON.stringify({serverFolder:'../other'})})).status,400);
  assert.equal((await request('/api/config',{method:'POST',headers,body:JSON.stringify({serverType:'vanilla',paperVersion:'26.3'})})).status,200);
  socket.terminate();
});
